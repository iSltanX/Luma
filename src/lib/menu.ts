/**
 * ما تسمح به حالةُ الشاشة من أفعال القائمة الأصلية.
 *
 * أحداث القائمة تصل من النواة عبر الجسر، **فلا يحجبها `inert`**: تلك
 * تُخرج شجرة الصفحة من التركيز والوصول، ولا شأن لها بحدثٍ لا يمرّ
 * بالشجرة أصلًا. وبنود القائمة مفعَّلة دائمًا، فالحجب قرارُ الواجهة.
 *
 * المنطق هنا لا في `App.svelte` لأنه القاعدة، والقاعدة تُختبَر —
 * ولا حزمة فحص في المشروع تشغّل قائمة macOS.
 */

export interface ScreenState {
  /** شاشة الإعدادات تغطّي المحرر. */
  settings: boolean;
  /** ورقة اختيار الخط فوقها. */
  fontSheet: boolean;
  /** معاينة نسخة من السجل — قراءة فقط. */
  preview: boolean;
}

/**
 * هل يصل التحرير إلى النص الذي يراه صاحبه؟
 *
 * **الخطر الذي تمنعه:** ⌘Z أمام الإعدادات كان يتراجع في المستند
 * المحجوب — والمستخدم يظنّه يتراجع عن تغيير إعداد، وهو أشيع ما يُضغط
 * بعده — ثم يثبّت الحفظُ التلقائي المحوَ على القرص. والمعاينة قراءةٌ
 * فقط بقرار ثابت (`Luma.md` §٩)، فلا يُكتب فيها بأي طريق.
 */
export function editingReaches(state: ScreenState): boolean {
  return !state.settings && !state.fontSheet && !state.preview;
}
