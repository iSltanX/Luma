/**
 * قرار الإغلاق حين لا يصل النص القرص — **القاعدة هنا لا في الشاشة**.
 *
 * كان مدفونًا داخل ردّ نداء `listen` في `App.svelte`، فلم يكن في
 * `npm run verify` سطرٌ يلمسه: من نقل لقطة التحذير إلى ما بعد الحفظ،
 * أو رفع حارس إعادة الدخول، أو حذف إغلاق الطبقة الحاجبة — أعاد عطلًا
 * يفقد نصًّا، والاختبارات كلها خضراء. والقاعدة تُختبَر (كما في
 * `lib/menu.ts`)، فأُخرجت هنا وكلُّ أثرٍ يُحقَن فيها.
 *
 * ## القاعدة
 *
 * «فرصة استرجاع صريحة عند الإغلاق» — `Luma.md` §٥ **ثابت** — فرصةٌ
 * **لا حبس**: يُحذَّر الكاتب مرة، ويُقال له ثمنُ الإصرار، ثم يُحترم
 * إصراره. والإنهاء القسري وحده ليس مخرجًا: هو يقتل النسخة الوحيدة من
 * نصّه، أي الخسارة التي وُضع الرفض ليمنعها.
 */

import type { FlushOutcome } from "./autosave";

/** سبب عدم الاستقرار الذي حُذِّر عليه. */
export type WarnReason = "refused" | "busy";

export interface CloseEffects {
  /** كتابة فورية لما في البُفر. */
  flush: () => Promise<FlushOutcome>;
  /** يُخلي ما يحجب التحذير عن العين وعن قارئ الشاشة. */
  clearOverlays: () => void;
  /** يعرض التحذير بسببه. */
  warn: (because: WarnReason) => void;
  /** يُبلّغ النواة أن الإغلاق رُفض فتُعيد فتح مزلاجها. */
  decline: () => Promise<void>;
  /** يهدم النافذة فعلًا. */
  destroy: () => Promise<void>;
}

export function createCloseRequest(fx: CloseEffects) {
  /**
   * سببُ آخر تحذير عُرض، أو `null` إن لم يُعرض شيء.
   *
   * **يحمل السبب لا بتًّا عاريًا.** بتٌّ واحد كان يجعل تحذير `busy`
   * الحميد («لا عطل — أمهله لحظة») يستهلك الفرصة، فإذا فشل القرص فعلًا
   * بعده لم يُعرض تحذير `refused` أبدًا — وهو وحده الذي فيه العلاج
   * (مساحة أو أذونات) وصِدقُ حجم الخسارة. فيُهدَم على نصّ لم يُحذَّر
   * عليه، والرسالة الحميدة باقية على الشاشة تكذّب الحال.
   */
  let warnedFor: WarnReason | null = null;
  /** طلبٌ يعمل الآن — لا تتوازى نسختان على جلسة واحدة. */
  let busy = false;

  async function request(): Promise<void> {
    if (busy) {
      // **الطلب يُسقَط، والمزلاج يُفتح.** النواة أخذت مزلاجها قبل أن
      // تبثّ، فإسقاطُ الطلب صامتًا يتركه مأخوذًا إلى الأبد: الزر الأحمر
      // و⌘W يُمنعان ولا يُبثّ لهما شيء — بابٌ ميت لا صوت له.
      await fx.decline();
      return;
    }
    busy = true;
    try {
      // اللقطة قبل الكتابة: الاستنزاف نفسه قد يبثّ «محفوظ» فيُصفّر
      // التحذير الذي نحن بصدد تقييمه (`noteSaved`)، فيُحذَّر الكاتب في
      // كل محاولة ولا يُغلق أبدًا — حبسٌ من باب آخر.
      const warned = warnedFor;
      const wrote = await fx.flush();

      // **تبدُّل السبب تحذيرٌ جديد.** تحذيرٌ عن «ما زال يصل» لا يصلح
      // إذنًا للهدم حين صار القرص يرفض: ثمنُ الإصرار اختلف.
      if (!wrote.settled && warned !== wrote.because) {
        fx.clearOverlays();
        fx.warn(wrote.because);
        warnedFor = wrote.because;
        await fx.decline();
        return;
      }

      await fx.destroy();
    } finally {
      busy = false;
    }
  }

  /** حفظٌ نجح: التحذير السابق لم يعد يمثّل الحال. */
  function noteSaved(): void {
    warnedFor = null;
  }

  return { request, noteSaved };
}
