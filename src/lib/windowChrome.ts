/**
 * جانب أزرار النافذة — **يُقاس ولا يُفترض**.
 *
 * [ADR ٠٠٠٣](../../docs/decisions/0003-macos-rtl-window-chrome.md):
 * «الحشوة المحجوزة تتبع جانب الأزرار الفعلي كما يقرره النظام… أيّهما
 * لأيٍّ يُقاس ولا يُفترض». والقياس نفسه — إحداثي **س** الحقيقي لزرّ
 * الإغلاق — يأتي من النواة (`window_controls_x` في `src-tauri/src/lib.rs`،
 * قياسٌ عبر AppKit لا استنتاجٌ من اللغة). هذه الدالة هي الخطوة الثانية
 * وحدها: تحويل ذلك الإحداثي إلى جانب.
 *
 * كانت الخطوتان معًا مطويّتين سطرًا واحدًا داخل `App.svelte`، بلا
 * اختبار — بند ب/٢١ في `docs/audit/AUDIT-2026-08-27.md`. والفحص الذاتي
 * القائم (`src/dev/selftest.ts`) يقرأ **نفس** السمة التي تشتقّها هذه
 * الدالة ليقارن بها التخطيط، فقلبُ المقارنة هنا ينقلب معه ذلك الفحص
 * أيضًا ويبقى أخضر — فحصٌ ذاتيّ الاتساق لا يكشف شيئًا. هذا الاختبار
 * وحده يقارن بثابتٍ خارجي: رقمًا حرفيًا لا الدالة بنفسها.
 */
export type WindowControlsSide = "left" | "right";

/**
 * `x` إحداثي زرّ الإغلاق داخل النافذة، و`viewportWidth` عرضها —
 * وحدة القياس واحدة في الطرفين لأن نافذة العرض تملأ النافذة
 * (`titleBarStyle: Overlay`).
 */
export function deriveWindowControlsSide(
  x: number,
  viewportWidth: number,
): WindowControlsSide {
  return x < viewportWidth / 2 ? "left" : "right";
}
