/**
 * حدود الجُملة العربية — حسابٌ خالص بلا DOM ولا ProseMirror.
 *
 * منفصلٌ عن `EditorCore` لأنه قاعدة تُختبَر لا تنفيذٌ يُشغَّل، ولأن
 * تحميل نواة المحرر في الاختبار يجرّ معه شجرة عرض لا حاجة إليها —
 * الفصل نفسه الذي في `blocks.ts`.
 */

/**
 * النقطة والتعجّب والسؤال والفاصلة المنقوطة وثلاث نقاط.
 *
 * `،` لا تُنهي جملة — تفصل عبارات داخل الجملة الواحدة — وتُترك عمدًا.
 */
const SENTENCE_END = /[.!؟?؛…]+[\s]*/g;

/**
 * حدود الجملة التي يقع فيها موضعٌ داخل نصّ.
 *
 * تُعاد بإزاحات داخل النص نفسه؛ ومن لا جملة فيه (فقرة بلا ترقيم) يعود
 * بالفقرة كلها — وهو السلوك الصحيح: النص كتلةٌ واحدة فعلًا.
 *
 * **موضعٌ عند حدّ الجملة الأخيرة ينتمي إليها.** كان الشرط `pos < end`
 * وحده، فمن أنهى فقرته بنقطة — وهو ما يفعله كل كاتب — وقف مؤشره عند
 * `end` تمامًا فتجاوزَته الحلقةُ وعادت بمدًى فارغ عند آخر النص: تُخفَّت
 * الفقرة **كاملة** ولا يبقى فيها حرفٌ نشط. قِيس: ٥١ من ٥١ محرفًا
 * مخفَّتة، فتصير الشاشة كلها خافتة ولا شيء «في التركيز».
 */
export function sentenceAt(
  text: string,
  pos: number,
): { start: number; end: number } {
  let start = 0;
  SENTENCE_END.lastIndex = 0;
  let m: RegExpExecArray | null;
  while ((m = SENTENCE_END.exec(text)) !== null) {
    const end = m.index + m[0].length;
    if (pos < end || end >= text.length) return { start, end };
    start = end;
  }
  return { start, end: text.length };
}
